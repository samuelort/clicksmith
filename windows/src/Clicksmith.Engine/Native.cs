    public static extern bool WTSUnRegisterSessionNotification(IntPtr hWnd);

    /// <summary>Executable file name of a window's process, e.g. "ms-teams.exe"; null if unknown.</summary>
    public static string? ProcessExeName(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero) return null;
        GetWindowThreadProcessId(hwnd, out var pid);
        if (pid == 0) return null;
        var h = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid);
        if (h == IntPtr.Zero) return null;
        try
        {
            var sb = new StringBuilder(1024);
            uint size = (uint)sb.Capacity;
            return QueryFullProcessImageName(h, 0, sb, ref size) ? System.IO.Path.GetFileName(sb.ToString()).ToLowerInvariant() : null;
        }
        finally { CloseHandle(h); }
    }
}
